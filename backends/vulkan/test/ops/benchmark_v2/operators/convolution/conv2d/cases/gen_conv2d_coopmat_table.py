"""Selection table of the opt-in switch ETVK_CONV2D_COOPMAT
(runtime/.../conv2d/Conv2dCoopmatTable.h, study changes
conv2d-coopmat-model-switch, conv2d-coopmat-direct-gather and
conv2d-coopmat-evidence-hardening). Two steps (design D4 of
conv2d-coopmat-evidence-hardening):

    gen_conv2d_coopmat_table.py nominate --out FILE [--decisions FILE] SWEEP_DIR...
    gen_conv2d_coopmat_table.py table [--check] [--decisions FILE] CONFIRMATION_DIR...

A session directory holds session.json (per configuration the route time of
each arm over its runs, the times of every run, and the configuration's A/A
band) and coopmat-properties.json (the device's vendor and device ID).

nominate: sweep sessions only nominate. The sessions of one device are used
together, the first the reference; an arm of another session counts for a
configuration only when that session's auto agrees with the reference's within
the larger of the two A/A bands (design D6 of conv2d-coopmat-direct-gather).
Per device and configuration the nominated arms are, per route, the arm with
the largest ratio t(auto) / t(arm) against the auto of its own session among
the arms that passed validation in every run (at most three). Diagnostic and
control arms are never nominated. --decisions writes the sweep decision of
each configuration under the gate below (the replay of the earlier tables);
no table is written from sweep sessions.

table: one confirmation session per device times auto, A' (auto again) and
the nominated arms of each configuration. The row is the nominated arm with
the lowest median route time in the session, if t(auto) / t(arm) is at least
MIN_RATIO and exceeds 1 + the band, and the gate holds.

Gate (design D3): the A/A band (max over runs of 2 |A - A'| / (A + A')) is at
most MAX_BAND, the stock spread ((max - min) / median over every run of auto
and A') and the arm spread (the same over the arm's runs) are each at most
MAX_SPREAD. A configuration without a row has exactly one reason code:
unsupported (every arm refused by eligibility), validation (an arm failed the
reference), not-timed, unstable (the band or a spread above its limit),
below-threshold.
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = (
    HERE.parents[6] / "runtime/graph/ops/impl/convolution/conv2d/Conv2dCoopmatTable.h"
)
CONFIGS = HERE / "model_sweep_configs.json"
MIN_RATIO = 1.05
MAX_BAND = 0.10
MAX_SPREAD = 0.10
STOCK = ("auto", "A'")
# Arms that never become a row: staged-once diagnostics, the raw direct
# weight-load probes and their controls, and the matrix-instruction controls.
NOT_ROUTABLE = ("_diag_once", "_dlprobe", "_dlctl", "_simt")
REASONS = ("unsupported", "validation", "not-timed", "unstable", "below-threshold")

HEADER = """/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 * All rights reserved.
 *
 * This source code is licensed under the BSD-style license found in the
 * LICENSE file in the root directory of this source tree.
 */

// Generated by backends/vulkan/test/ops/benchmark_v2/operators/convolution/
// conv2d/cases/gen_conv2d_coopmat_table.py from the saved confirmation
// sessions of change conv2d-coopmat-evidence-hardening; do not edit.

#pragma once

#include <array>
#include <cstdint>

namespace vkcompute {

// A measured convolution configuration and the cooperative-matrix variant
// that ran it fastest on one device (vendor and device ID).
struct Conv2dCoopmatTableRow final {
  uint32_t vendor_id;
  uint32_t device_id;
  int64_t c_in;
  int64_t c_out;
  int64_t k_h;
  int64_t k_w;
  int64_t stride_h;
  int64_t stride_w;
  int64_t padding_h;
  int64_t padding_w;
  int64_t dilation_h;
  int64_t dilation_w;
  int64_t in_h;
  int64_t in_w;
  const char* variant;
};
"""


def route_of(arm):
    tokens = arm.split("_")
    if "dg" in tokens:
        return "direct_coopmat"
    return "im2col_coopmat" if "i2c" in tokens else "pw_coopmat"


def routable(arm):
    return arm not in STOCK and not any(tag in arm for tag in NOT_ROUTABLE)


def spread(values):
    return (max(values) - min(values)) / statistics.median(values)


def stock_spread(sh):
    runs = [t for a in STOCK for t in (sh["arms"].get(a) or {}).get("runs") or []]
    return spread(runs) if runs else None


def no_time_code(arm_records):
    """The reason code of a configuration none of whose arms has a time, from
    the arms' run statuses (records of i2c.py summarize: "reason" lists them)."""
    reasons = [x.get("reason") or "" for x in arm_records]
    if any("FAIL" in r or "ERROR" in r for r in reasons):
        return "validation"
    if reasons and all(r.startswith("SKIP") and "PASS" not in r for r in reasons):
        return "unsupported"
    return "not-timed"


def gate(x):
    """(code, text) of why a timed arm cannot be a row, or None. x: ratio,
    band, stock_spread, spread."""
    if x["band"] > MAX_BAND:
        return "unstable", f"A/A band {x['band']:.3f} above {MAX_BAND}"
    if x["stock_spread"] > MAX_SPREAD:
        return "unstable", f"stock spread {x['stock_spread']:.3f} above {MAX_SPREAD}"
    if x["spread"] > MAX_SPREAD:
        return "unstable", f"arm spread {x['spread']:.3f} above {MAX_SPREAD}"
    if x["ratio"] < MIN_RATIO:
        return "below-threshold", f"ratio {x['ratio']:.3f} below {MIN_RATIO}"
    if x["ratio"] - 1 <= x["band"]:
        return (
            "below-threshold",
            f"ratio {x['ratio']:.3f} within the A/A band {x['band']:.3f}",
        )
    return None


#
# Sweep sessions: nomination and replay decisions
#


def collect(shape, sessions, ref_auto, ref_band):
    """The arms of every session of the device that count for the
    configuration: (candidates, untimed arm records, sessions used, sessions
    skipped)."""
    ref_name = sessions[0][0]
    candidates, untimed, used, skipped = {}, {}, [], []
    for name, s in sessions:
        sh = s["shapes"].get(shape)
        if sh is None:
            continue
        auto = (sh["arms"].get("auto") or {}).get("t")
        band = s["band"].get(shape)
        if name != ref_name:
            if auto is None or band is None:
                skipped.append(f"{name}: no A/A pair")
                continue
            diff = 2 * abs(auto - ref_auto) / (auto + ref_auto)
            limit = max(band, ref_band)
            if diff > limit:
                skipped.append(
                    f"{name}: auto {auto:.1f} us against {ref_auto:.1f} us, "
                    f"{diff:.3f} above the band {limit:.3f}"
                )
                continue
        used.append(name)
        for arm, x in sh["arms"].items():
            if not routable(arm):
                continue
            if x.get("t"):
                untimed.pop(arm, None)
                candidates[arm] = {
                    "ratio": auto / x["t"],
                    "t": x["t"],
                    "t_auto": auto,
                    "band": max(band, ref_band),
                    "stock_spread": stock_spread(sh),
                    "spread": spread(x["runs"]),
                    "session": name,
                }
            else:
                candidates.pop(arm, None)
                untimed[arm] = x
    return candidates, untimed, used, skipped


def nominate(shape, sessions):
    """(nomination, sweep decision) of one configuration on one device.
    nomination: {"arms": [arm per route], "reason": code when none}. The sweep
    decision applies the gate to every arm (each against its own session) and
    takes the qualifying arm with the lowest route time."""
    ref = sessions[0][1]
    ref_arms = (ref["shapes"].get(shape) or {}).get("arms", {})
    ref_auto = (ref_arms.get("auto") or {}).get("t")
    ref_band = ref["band"].get(shape)
    if ref_band is None or ref_auto is None:
        text = "route auto has no time in every run (no A/A pair)"
        return {"arms": [], "reason": "not-timed"}, ({}, "not-timed", text)
    candidates, untimed, used, skipped = collect(shape, sessions, ref_auto, ref_band)
    info = {"sessions_used": used, "sessions_skipped": skipped}
    by_route = {}
    for arm, x in candidates.items():
        r = route_of(arm)
        if r not in by_route or x["ratio"] > candidates[by_route[r]]["ratio"]:
            by_route[r] = arm
    nomination = {"arms": [by_route[r] for r in sorted(by_route)]}
    info["nominated"] = {by_route[r]: candidates[by_route[r]] for r in sorted(by_route)}
    if not candidates:
        code = no_time_code(list(untimed.values()))
        nomination["reason"] = code
        text = "no arm has a time in every run" + (
            f" ({', '.join(sorted(untimed))})" if untimed else ""
        )
        return nomination, (info, code, text)
    passing = [a for a in candidates if gate(candidates[a]) is None]
    best = min(passing or candidates, key=lambda a: candidates[a]["t"])
    x = candidates[best]
    info.update(
        {
            "best": best,
            "route": route_of(best),
            "session": x["session"],
            "ratio": x["ratio"],
            "band": x["band"],
            "stock_spread": x["stock_spread"],
            "spread": x["spread"],
            "t_auto": x["t_auto"],
            "t_best": x["t"],
            "max_ratio": max(c["ratio"] for c in candidates.values()),
            "passing_arms": len(passing),
        }
    )
    if passing:
        return nomination, (info, None, None)
    code, text = gate(x)
    return nomination, (info, code, f"no arm meets the criteria; the fastest: {text}")


#
# Confirmation sessions: the table
#


def confirm(shape, s):
    """(info, code, text) of one configuration in a confirmation session;
    code None means a row (info["best"])."""
    nomination = s["nominations"][shape]
    sh = s["shapes"].get(shape)
    info = {"nominated": nomination["arms"]}
    if not nomination["arms"]:
        return info, nomination["reason"], "no arm nominated by the sweep sessions"
    auto = (sh["arms"].get("auto") or {}).get("t")
    band = s["band"].get(shape)
    if auto is None or band is None:
        return info, "not-timed", "route auto has no time in every run (no A/A pair)"
    stock = stock_spread(sh)
    info.update({"t_auto": auto, "band": band, "stock_spread": stock})
    arms, untimed = {}, []
    for arm in nomination["arms"]:
        x = sh["arms"].get(arm) or {}
        if x.get("t"):
            arms[arm] = {
                "t": x["t"],
                "runs": x["runs"],
                "ratio": auto / x["t"],
                "band": band,
                "stock_spread": stock,
                "spread": spread(x["runs"]),
            }
        else:
            untimed.append(x or {"reason": "not timed"})
    info["arms"] = arms
    candidates = {a: x for a, x in arms.items() if routable(a)}
    info["not_routable"] = sorted(set(arms) - set(candidates))
    if not candidates:
        return (
            info,
            no_time_code(untimed),
            "no nominated arm has a time in every run",
        )
    best = min(candidates, key=lambda a: candidates[a]["t"])
    x = candidates[best]
    info.update(
        {
            "best": best,
            "route": route_of(best),
            "ratio": x["ratio"],
            "spread": x["spread"],
            "t_best": x["t"],
            "max_ratio": max(c["ratio"] for c in candidates.values()),
        }
    )
    rejected = gate(x)
    if rejected is None:
        return info, None, None
    return info, rejected[0], f"the fastest nominated arm: {rejected[1]}"


def load(session_dir):
    s = json.loads((session_dir / "session.json").read_text())
    props = json.loads((session_dir / "coopmat-properties.json").read_text())[0]
    vendor, device = props["validation"]["vendor_device_id"].split(":")
    return (
        "/".join(session_dir.resolve().parts[-3:]),
        s,
        (int(vendor, 16), int(device, 16)),
    )


def record(ref, c, info, code, text):
    assert code is None or code in REASONS, code
    return {
        "device": ref["device"],
        "device_name": ref["device_name"],
        "label": c["label"],
        **info,
        "row": code is None,
        "reason": code,
        "detail": text,
    }


def rows_of(name, s, ids, configs):
    rows, decisions = [], []
    for shape in s["nominations"]:
        c = configs[shape.removeprefix("sweep ")]
        info, code, text = confirm(shape, s)
        decisions.append({**record(s, c, info, code, text), "session": name})
        if code is None:
            rows.append(
                {
                    "vendor": ids[0],
                    "device": ids[1],
                    "c": c,
                    "variant": f"conv2d_pw_coopmat_{info['best']}_half",
                    "comment": f"{s['device_name']}, {s['driver']}: {c['label']}, "
                    f"{info['ratio']:.2f}x",
                }
            )
    return rows, decisions


def header(rows):
    lines = [HEADER, "// clang-format off"]
    lines.append(
        "inline constexpr std::array<Conv2dCoopmatTableRow, "
        f"{len(rows)}> kConv2dCoopmatTable = {{{{"
    )
    for r in rows:
        c = r["c"]
        values = [c["cin"], c["cout"], c["kh"], c["kw"], *c["stride"]]
        values += [*c["padding"], *c["dilation"], c["h"], c["w"]]
        lines.append(f"    // {r['comment']}")
        lines.append(
            f"    {{0x{r['vendor']:04x}, 0x{r['device']:04x}, "
            + ", ".join(str(v) for v in values)
            + f', "{r["variant"]}"}},'
        )
    lines += ["}};", "// clang-format on", "", "} // namespace vkcompute"]
    return "\n".join(lines) + "\n"


def by_device(dirs):
    groups = {}
    for d in dirs:
        name, s, ids = load(d)
        groups.setdefault(ids, []).append((name, s))
    return groups


def run_nominate(args, configs):
    nominations, decisions = {}, []
    for sessions in by_device(args.sessions).values():
        ref = sessions[0][1]
        dev = nominations.setdefault(ref["device"], {})
        for shape in ref["shapes"]:
            nomination, (info, code, text) = nominate(shape, sessions)
            dev[shape] = nomination
            c = configs[shape.removeprefix("sweep ")]
            decisions.append(record(ref, c, info, code, text))
    args.out.write_text(json.dumps(nominations, indent=1) + "\n")
    print(
        f"nominations for {sum(len(v) for v in nominations.values())} "
        f"configurations on {len(nominations)} devices"
    )
    return decisions


def run_table(args, configs):
    rows, decisions = [], []
    for ids, sessions in by_device(args.sessions).items():
        for name, s in sessions:
            if not s.get("confirmation") or "nominations" not in s:
                sys.exit(
                    f"{name} is not a confirmation session: sweep sessions only "
                    "nominate; the table is generated from confirmation sessions"
                )
        if len(sessions) != 1:
            sys.exit(f"{len(sessions)} confirmation sessions for device {ids}")
        r, dec = rows_of(*sessions[0], ids, configs)
        rows += r
        decisions += dec
    text = header(rows)
    print(f"{len(rows)} rows from {len(decisions)} configurations")
    if args.check:
        if TABLE.read_text() != text:
            sys.exit(f"out of date: {TABLE.name}")
    else:
        TABLE.write_text(text)
    return decisions


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("step", choices=("nominate", "table"))
    parser.add_argument("sessions", type=Path, nargs="+")
    parser.add_argument("--out", type=Path, help="nominate: the nominations file")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--decisions", type=Path)
    args = parser.parse_args()
    configs = {c["label"]: c for c in json.loads(CONFIGS.read_text())}
    if args.step == "nominate":
        if args.out is None or args.check:
            sys.exit("nominate needs --out and writes no table")
        decisions = run_nominate(args, configs)
    else:
        decisions = run_table(args, configs)
    if args.decisions:
        args.decisions.write_text(json.dumps(decisions, indent=1) + "\n")


if __name__ == "__main__":
    main()

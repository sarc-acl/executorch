"""Writes the selection table of the opt-in switch ETVK_CONV2D_COOPMAT
(runtime/.../conv2d/Conv2dCoopmatTable.h, study changes
conv2d-coopmat-model-switch and conv2d-coopmat-direct-gather) from saved sweep
sessions:

    gen_conv2d_coopmat_table.py [--check] [--decisions FILE] SESSION_DIR...

SESSION_DIR holds session.json (summary of a model_sweep_performance.json
session: per configuration the route time of each arm over its runs and the
configuration's A/A band) and coopmat-properties.json (the device's vendor and
device ID). The sessions of one device are used together; the first of them is
the reference. An arm of another session of the device counts for a
configuration only when that session's route auto agrees with the reference's
within the larger of the two A/A bands (design D6 of
conv2d-coopmat-direct-gather); where several sessions time the same arm, the
later one on the command line counts. Per device and configuration the table
has the arm with the largest ratio t(auto) / t(arm), each arm against the
auto of its own session, when it passed validation in every run, the ratio is
at least MIN_RATIO and exceeds 1 + the band, and the band (the larger of the
reference's and the arm's session's) is at most MAX_BAND; otherwise no row.
--decisions writes every configuration's decision (row or reason) as JSON.
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = (
    HERE.parents[6] / "runtime/graph/ops/impl/convolution/conv2d/Conv2dCoopmatTable.h"
)
CONFIGS = HERE / "model_sweep_configs.json"
MIN_RATIO = 1.05
MAX_BAND = 0.10

HEADER = """/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 * All rights reserved.
 *
 * This source code is licensed under the BSD-style license found in the
 * LICENSE file in the root directory of this source tree.
 */

// Generated by backends/vulkan/test/ops/benchmark_v2/operators/convolution/
// conv2d/cases/gen_conv2d_coopmat_table.py from the saved sweep sessions of
// changes conv2d-coopmat-model-switch and conv2d-coopmat-direct-gather; do not
// edit.

#pragma once

#include <array>
#include <cstdint>

namespace vkcompute {

// A measured convolution configuration and the cooperative-matrix variant
// that ran it fastest on one device (vendor and device ID).
struct Conv2dCoopmatTableRow final {
  uint32_t vendor_id;
  uint32_t device_id;
  int64_t c_in;
  int64_t c_out;
  int64_t k_h;
  int64_t k_w;
  int64_t stride_h;
  int64_t stride_w;
  int64_t padding_h;
  int64_t padding_w;
  int64_t dilation_h;
  int64_t dilation_w;
  int64_t in_h;
  int64_t in_w;
  const char* variant;
};
"""


def route_of(arm):
    if arm.endswith("_dg"):
        return "direct_coopmat"
    return "im2col_coopmat" if arm.endswith("_i2c") else "pw_coopmat"


def decide(shape, sessions):
    """sessions: [(name, session summary)] of one device, the reference
    first. Returns (info, reason); reason None means a row."""
    ref_name, ref = sessions[0]
    ref_arms = (ref["shapes"].get(shape) or {}).get("arms", {})
    ref_auto = (ref_arms.get("auto") or {}).get("t")
    ref_band = ref["band"].get(shape)
    if ref_band is None or ref_auto is None:
        return {}, "route auto has no time in every run (no A/A pair)"
    candidates, timed, used, skipped = {}, set(), [], []
    for name, s in sessions:
        sh = s["shapes"].get(shape)
        if sh is None:
            continue
        auto = (sh["arms"].get("auto") or {}).get("t")
        band = s["band"].get(shape)
        if name != ref_name:
            if auto is None or band is None:
                skipped.append(f"{name}: no A/A pair")
                continue
            diff = 2 * abs(auto - ref_auto) / (auto + ref_auto)
            limit = max(band, ref_band)
            if diff > limit:
                skipped.append(
                    f"{name}: auto {auto:.1f} us against {ref_auto:.1f} us, "
                    f"{diff:.3f} above the band {limit:.3f}"
                )
                continue
        used.append(name)
        for arm, x in sh["arms"].items():
            if arm in ("auto", "A'"):
                continue
            timed.add(arm)
            if x.get("t"):
                candidates[arm] = {
                    "ratio": auto / x["t"],
                    "t": x["t"],
                    "t_auto": auto,
                    "band": max(band, ref_band),
                    "session": name,
                }
            else:
                candidates.pop(arm, None)
    info = {"sessions_used": used, "sessions_skipped": skipped}
    by_route = {}
    for arm, x in candidates.items():
        r = route_of(arm)
        if r not in by_route or x["ratio"] > candidates[by_route[r]]["ratio"]:
            by_route[r] = arm
    info["best_by_route"] = {
        r: {"arm": a, **candidates[a]} for r, a in sorted(by_route.items())
    }
    if not candidates:
        failed = sorted(timed)
        return info, "no variant passed validation in every run" + (
            f" ({', '.join(failed)})" if failed else ""
        )
    best = max(candidates, key=lambda a: candidates[a]["ratio"])
    x = candidates[best]
    band = x["band"]
    info.update(
        {
            "best": best,
            "route": route_of(best),
            "session": x["session"],
            "ratio": x["ratio"],
            "band": band,
            "t_auto": x["t_auto"],
            "t_best": x["t"],
        }
    )
    if band > MAX_BAND:
        return info, f"A/A band {band:.3f} above {MAX_BAND}"
    if x["ratio"] < MIN_RATIO:
        return info, f"best ratio {x['ratio']:.3f} below {MIN_RATIO}"
    if x["ratio"] - 1 <= band:
        return info, f"best ratio {x['ratio']:.3f} within the A/A band {band:.3f}"
    return info, None


def load(session_dir):
    s = json.loads((session_dir / "session.json").read_text())
    props = json.loads((session_dir / "coopmat-properties.json").read_text())[0]
    vendor, device = props["validation"]["vendor_device_id"].split(":")
    return (
        "/".join(session_dir.resolve().parts[-3:]),
        s,
        (int(vendor, 16), int(device, 16)),
    )


def rows_of(sessions, ids, configs):
    ref = sessions[0][1]
    rows, decisions = [], []
    for shape in ref["shapes"]:
        c = configs[shape.removeprefix("sweep ")]
        info, reason = decide(shape, sessions)
        decisions.append(
            {
                "device": ref["device"],
                "device_name": ref["device_name"],
                "label": c["label"],
                **info,
                "row": reason is None,
                "reason": reason,
            }
        )
        if reason is None:
            rows.append(
                {
                    "vendor": ids[0],
                    "device": ids[1],
                    "c": c,
                    "variant": f"conv2d_pw_coopmat_{info['best']}_half",
                    "comment": f"{ref['device_name']}, {ref['driver']}: {c['label']}, "
                    f"{info['ratio']:.2f}x",
                }
            )
    return rows, decisions


def header(rows):
    lines = [HEADER, "// clang-format off"]
    lines.append(
        "inline constexpr std::array<Conv2dCoopmatTableRow, "
        f"{len(rows)}> kConv2dCoopmatTable = {{{{"
    )
    for r in rows:
        c = r["c"]
        values = [c["cin"], c["cout"], c["kh"], c["kw"], *c["stride"]]
        values += [*c["padding"], *c["dilation"], c["h"], c["w"]]
        lines.append(f"    // {r['comment']}")
        lines.append(
            f"    {{0x{r['vendor']:04x}, 0x{r['device']:04x}, "
            + ", ".join(str(v) for v in values)
            + f', "{r["variant"]}"}},'
        )
    lines += ["}};", "// clang-format on", "", "} // namespace vkcompute"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sessions", type=Path, nargs="*")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--decisions", type=Path)
    args = parser.parse_args()
    configs = {c["label"]: c for c in json.loads(CONFIGS.read_text())}
    groups = {}
    for d in args.sessions:
        name, s, ids = load(d)
        groups.setdefault(ids, []).append((name, s))
    rows, decisions = [], []
    for ids, sessions in groups.items():
        r, dec = rows_of(sessions, ids, configs)
        rows += r
        decisions += dec
    text = header(rows)
    if args.decisions:
        args.decisions.write_text(json.dumps(decisions, indent=1) + "\n")
    print(f"{len(rows)} rows from {len(decisions)} configurations")
    if args.check:
        if TABLE.read_text() != text:
            sys.exit(f"out of date: {TABLE.name}")
    else:
        TABLE.write_text(text)


if __name__ == "__main__":
    main()

"""Selection table of the opt-in switch ETVK_CONV2D_COOPMAT
(runtime/.../conv2d/Conv2dCoopmatTable.h, study changes
conv2d-coopmat-model-switch, conv2d-coopmat-direct-gather,
conv2d-coopmat-evidence-hardening and conv2d-coopmat-conservative-gate). Two
steps (design D4 of conv2d-coopmat-evidence-hardening):

    gen_conv2d_coopmat_table.py nominate --out FILE [--decisions FILE] SWEEP_DIR...
    gen_conv2d_coopmat_table.py table --nominations FILE... [--check]
        [--decisions FILE] CONFIRMATION_DIR...

A session directory holds session.json (per configuration the route time of
each arm over its runs, the times of every run, and the configuration's A/A
band) and coopmat-properties.json (the device's vendor and device ID).

Rule (design D1 of conv2d-coopmat-conservative-gate): within one session,
stock_best is the fastest run of auto and A', and an arm's worst is its
slowest run. An arm qualifies if it passed validation in every run and
stock_best / worst is at least MIN_RATIO. Timing spread and the A/A band are
recorded as descriptions; they do not decide.

nominate: sweep sessions only nominate. Every timed arm of every sweep session
of the device is one observation, judged by the rule within its own session,
validation included: an arm that failed validation in a session gives no
observation there. Per device and
configuration the nominated arms are, per route, the arm of the qualifying
observation with the largest ratio of medians t(auto) / t(arm) against the auto
of its own session (at most three). Without a qualifying arm the configuration
has no nominee and keeps its reason code. Diagnostic and control arms are never
nominated. --decisions writes the sweep decision of each configuration (the
qualifying observation with the lowest worst); no table is written from sweep
sessions.

table: confirmation sessions time auto, A' (auto again) and the nominated
arms, CONFIRM_RUNS interleaved runs in which each even run reverses the arm
order of the odd run before it (the summary records schedule
"paired-reverse" only when the saved runs follow it). The nominations are
the nominate output (--nominations). Per device and configuration the decision
uses the last confirmation session on the command line that timed every
nominee together with both stock arms; the stock arms and a qualifying arm must
have passed all CONFIRM_RUNS runs. The row is the qualifying nominated arm with
the lowest worst, and the table records its ratio stock_best / worst. There is
no device-level disqualification: every configuration is decided on its own.

A configuration without a row has exactly one reason code: unsupported (every
arm refused by eligibility), validation (an arm or the stock route failed the
reference), not-timed, unstable (an arm wins on medians, t(auto) / t(arm) at
least MIN_RATIO, but none qualifies), below-threshold (no arm wins on
medians).
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = (
    HERE.parents[6] / "runtime/graph/ops/impl/convolution/conv2d/Conv2dCoopmatTable.h"
)
CONFIGS = HERE / "model_sweep_configs.json"
MIN_RATIO = 1.05
CONFIRM_RUNS = 5
STOCK = ("auto", "A'")
# Arms that never become a row: staged-once diagnostics, the raw direct
# weight-load probes and their controls, and the matrix-instruction controls.
NOT_ROUTABLE = ("_diag_once", "_dlprobe", "_dlctl", "_simt")
REASONS = ("unsupported", "validation", "not-timed", "unstable", "below-threshold")

HEADER = """/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 * All rights reserved.
 *
 * This source code is licensed under the BSD-style license found in the
 * LICENSE file in the root directory of this source tree.
 */

// Generated by backends/vulkan/test/ops/benchmark_v2/operators/convolution/
// conv2d/cases/gen_conv2d_coopmat_table.py from the saved confirmation
// sessions of change conv2d-coopmat-conservative-gate; do not edit. The ratio
// after each configuration is the fastest stock run of its confirmation
// session over the slowest run of the variant.

#pragma once

#include <array>
#include <cstdint>

namespace vkcompute {

// A measured convolution configuration and the cooperative-matrix variant
// whose slowest run beat every stock run on one device (vendor and device ID).
struct Conv2dCoopmatTableRow final {
  uint32_t vendor_id;
  uint32_t device_id;
  int64_t c_in;
  int64_t c_out;
  int64_t k_h;
  int64_t k_w;
  int64_t stride_h;
  int64_t stride_w;
  int64_t padding_h;
  int64_t padding_w;
  int64_t dilation_h;
  int64_t dilation_w;
  int64_t in_h;
  int64_t in_w;
  const char* variant;
};
"""


def route_of(arm):
    if arm.endswith("_dg"):
        return "direct_coopmat"
    return "im2col_coopmat" if arm.endswith("_i2c") else "pw_coopmat"


def routable(arm):
    return arm not in STOCK and not any(tag in arm for tag in NOT_ROUTABLE)


def spread(values):
    return (max(values) - min(values)) / statistics.median(values)


def stock_runs(sh):
    return [t for a in STOCK for t in (sh["arms"].get(a) or {}).get("runs") or []]


def stock_spread(sh):
    runs = stock_runs(sh)
    return spread(runs) if runs else None


def judged(sh, x):
    """A timed arm against the stock route of its session: route time, runs,
    ratio of medians, worst run, conservative ratio stock_best / worst and the
    spreads (descriptions)."""
    stock_best = min(stock_runs(sh))
    return {
        "t": x["t"],
        "runs": x["runs"],
        "ratio": sh["arms"]["auto"]["t"] / x["t"],
        "worst": max(x["runs"]),
        "conservative": stock_best / max(x["runs"]),
        "stock_best": stock_best,
        "stock_spread": stock_spread(sh),
        "spread": spread(x["runs"]),
    }


def qualifies(x):
    return x["conservative"] >= MIN_RATIO


def no_row(arms):
    """(code, text) for timed arms of which none qualifies."""
    on_medians = [x for x in arms if x["ratio"] >= MIN_RATIO]
    if on_medians:
        x = max(on_medians, key=lambda x: x["conservative"])
        return "unstable", (
            f"`{x['arm']}` wins on medians ({x['ratio']:.3f}) but fastest stock "
            f"run / its slowest run {x['conservative']:.3f} is below {MIN_RATIO}"
        )
    x = max(arms, key=lambda x: x["ratio"])
    return "below-threshold", (
        f"best ratio of medians {x['ratio']:.3f} (`{x['arm']}`) below {MIN_RATIO}"
    )


def no_time_code(arm_records):
    """The reason code of arms without a time, from their run statuses (records
    of i2c.py summarize: "reason" lists "<STATUS> <detail>" per distinct run
    outcome, joined by "; "). validation: an output failed the reference check
    in a run (FAIL); unsupported: every run was refused (SKIP); not-timed
    otherwise, including an error during setup or the run (ERROR)."""
    statuses = [
        [seg.split(" ", 1)[0] for seg in (x.get("reason") or "").split("; ")]
        for x in arm_records
    ]
    if any("FAIL" in st for st in statuses):
        return "validation"
    if statuses and all(set(st) == {"SKIP"} for st in statuses):
        return "unsupported"
    return "not-timed"


def stock_code(sh):
    """The reason code of a configuration whose stock arms (auto, A') lack a
    time: validation when one failed the reference in a run, not-timed
    otherwise."""
    records = [(sh or {}).get("arms", {}).get(a) or {} for a in STOCK]
    return "validation" if no_time_code(records) == "validation" else "not-timed"


#
# Sweep sessions: nomination and replay decisions
#


def observations(shape, sessions):
    """Every timed arm of every session of the device for the configuration,
    each judged against its own session's stock runs: (observations, untimed
    arm records, sessions used, sessions skipped). An arm that failed
    validation in a session has no time there and gives no observation from
    that session."""
    obs, untimed, used, skipped = [], [], [], []
    for name, s in sessions:
        sh = s["shapes"].get(shape)
        if sh is None:
            continue
        if not all((sh["arms"].get(a) or {}).get("t") for a in STOCK):
            skipped.append((name, stock_code(sh)))
            continue
        used.append(name)
        for arm, x in sh["arms"].items():
            if not routable(arm):
                continue
            if x.get("t"):
                obs.append(
                    {
                        "arm": arm,
                        **judged(sh, x),
                        "t_auto": sh["arms"]["auto"]["t"],
                        "band": s["band"].get(shape),
                        "session": name,
                    }
                )
            else:
                untimed.append(x)
    return obs, untimed, used, skipped


def nominate(shape, sessions):
    """(nomination, sweep decision) of one configuration on one device.
    nomination: {"arms": [arm per route], "reason" and "detail" when none}.
    Every arm observation is judged within its own session; per route the
    nominee is the qualifying observation with the largest ratio of medians.
    The sweep decision takes the qualifying observation with the lowest
    worst."""
    obs, untimed, used, skipped = observations(shape, sessions)
    info = {
        "sessions_used": used,
        "sessions_skipped": [f"{n}: no A/A pair ({c})" for n, c in skipped],
        "nominated": {},
    }
    if not used:
        # The stock route failed the reference in a session (validation), or
        # has no time in any (not-timed).
        code = (
            "validation" if any(c == "validation" for _, c in skipped) else "not-timed"
        )
        text = (
            "route auto or A' failed validation (no A/A pair)"
            if code == "validation"
            else "route auto has no time in every run (no A/A pair)"
        )
        return {"arms": [], "reason": code, "detail": text}, (info, code, text)
    if not obs:
        code = no_time_code(untimed)
        text = "no arm has a time in every run"
        return {"arms": [], "reason": code, "detail": text}, (info, code, text)
    passing = [o for o in obs if qualifies(o)]
    by_route = {}
    for o in passing:
        r = route_of(o["arm"])
        if r not in by_route or o["ratio"] > by_route[r]["ratio"]:
            by_route[r] = o
    nomination = {"arms": [by_route[r]["arm"] for r in sorted(by_route)]}
    info["nominated"] = {by_route[r]["arm"]: by_route[r] for r in sorted(by_route)}
    if passing:
        x = min(passing, key=lambda o: o["worst"])
    else:
        x = max(obs, key=lambda o: o["conservative"])
    info.update(
        {
            "best": x["arm"],
            "route": route_of(x["arm"]),
            "session": x["session"],
            "ratio": x["conservative"],
            "median_ratio": x["ratio"],
            "band": x["band"],
            "stock_spread": x["stock_spread"],
            "spread": x["spread"],
            "t_auto": x["t_auto"],
            "stock_best": x["stock_best"],
            "t_best": x["t"],
            "worst": x["worst"],
            "max_ratio": max(o["ratio"] for o in obs),
            "passing_observations": len(passing),
        }
    )
    if passing:
        return nomination, (info, None, None)
    code, text = no_row(obs)
    text = f"no arm qualifies in its session: {text}"
    nomination.update({"reason": code, "detail": text})
    return nomination, (info, code, text)


#
# Confirmation sessions: the table
#


def complete(x):
    """Whether an arm record holds CONFIRM_RUNS passing runs."""
    return bool(
        x
        and x.get("t")
        and x.get("passed_runs") == CONFIRM_RUNS
        and len(x.get("runs") or []) == CONFIRM_RUNS
    )


def covers(sh, nomination):
    """Whether a confirmation session's shape record timed every nominee
    together with both stock arms."""
    return sh is not None and all(
        a in sh["arms"] for a in (*STOCK, *nomination["arms"])
    )


def confirm(shape, s, nomination):
    """(info, code, text) of one configuration in a confirmation session that
    covers its nomination; code None means a row (info["best"])."""
    sh = s["shapes"].get(shape)
    info = {"nominated": nomination["arms"]}
    if not nomination["arms"]:
        return (
            info,
            nomination["reason"],
            "no nominee: "
            + nomination.get("detail", "no qualifying arm in the sweeps"),
        )
    if not all(complete(sh["arms"].get(a)) for a in STOCK):
        code = stock_code(sh)
        return (
            info,
            code,
            (
                "auto or A' failed validation (no A/A pair)"
                if code == "validation"
                else f"auto or A' without {CONFIRM_RUNS} passing runs (no A/A pair)"
            ),
        )
    info.update(
        {
            "t_auto": sh["arms"]["auto"]["t"],
            "stock_best": min(stock_runs(sh)),
            "band": s["band"].get(shape),
            "stock_spread": stock_spread(sh),
        }
    )
    arms, untimed = {}, []
    for arm in nomination["arms"]:
        x = sh["arms"].get(arm) or {}
        if complete(x):
            arms[arm] = judged(sh, x)
        else:
            untimed.append(x or {"reason": "not timed"})
    info["arms"] = arms
    candidates = {a: x for a, x in arms.items() if routable(a)}
    info["not_routable"] = sorted(set(arms) - set(candidates))
    if not candidates:
        return (
            info,
            no_time_code(untimed),
            f"no nominated arm has {CONFIRM_RUNS} passing runs",
        )
    qualifying = [a for a in candidates if qualifies(candidates[a])]
    if qualifying:
        best = min(qualifying, key=lambda a: candidates[a]["worst"])
    else:
        best = max(candidates, key=lambda a: candidates[a]["conservative"])
    x = candidates[best]
    info.update(
        {
            "best": best,
            "route": route_of(best),
            "ratio": x["conservative"],
            "median_ratio": x["ratio"],
            "spread": x["spread"],
            "t_best": x["t"],
            "worst": x["worst"],
            "max_ratio": max(c["ratio"] for c in candidates.values()),
        }
    )
    if qualifying:
        return info, None, None
    code, text = no_row([{"arm": a, **x} for a, x in candidates.items()])
    return info, code, f"no nominated arm qualifies: {text}"


def decide(shape, sessions, nomination):
    """(info, code, text, session name) from the last session that covers the
    nomination (or none, for a configuration without a nominee)."""
    if not nomination["arms"]:
        info, code, text = confirm(shape, {"shapes": {}, "band": {}}, nomination)
        return info, code, text, None
    for name, s in reversed(sessions):
        if covers(s["shapes"].get(shape), nomination):
            return (*confirm(shape, s, nomination), name)
    return (
        {"nominated": nomination["arms"]},
        "not-timed",
        "no confirmation session timed every nominee with both stock arms",
        None,
    )


def load(session_dir):
    s = json.loads((session_dir / "session.json").read_text())
    props = json.loads((session_dir / "coopmat-properties.json").read_text())[0]
    vendor, device = props["validation"]["vendor_device_id"].split(":")
    return (
        "/".join(session_dir.resolve().parts[-3:]),
        s,
        (int(vendor, 16), int(device, 16)),
    )


def record(ref, c, info, code, text):
    assert code is None or code in REASONS, code
    return {
        "device": ref["device"],
        "device_name": ref["device_name"],
        "label": c["label"],
        **info,
        "row": code is None,
        "reason": code,
        "detail": text,
    }


def rows_of(sessions, nominations, ids, configs):
    ref = sessions[-1][1]
    rows, decisions = [], []
    for shape, nomination in nominations.items():
        c = configs[shape.removeprefix("sweep ")]
        info, code, text, name = decide(shape, sessions, nomination)
        decisions.append({**record(ref, c, info, code, text), "session": name})
        if code is None:
            rows.append(
                {
                    "vendor": ids[0],
                    "device": ids[1],
                    "c": c,
                    "variant": f"conv2d_pw_coopmat_{info['best']}_half",
                    "comment": f"{ref['device_name']}, {ref['driver']}: {c['label']}, "
                    f"{info['ratio']:.2f}x",
                }
            )
    return rows, decisions


def header(rows):
    lines = [HEADER, "// clang-format off"]
    lines.append(
        "inline constexpr std::array<Conv2dCoopmatTableRow, "
        f"{len(rows)}> kConv2dCoopmatTable = {{{{"
    )
    for r in rows:
        c = r["c"]
        values = [c["cin"], c["cout"], c["kh"], c["kw"], *c["stride"]]
        values += [*c["padding"], *c["dilation"], c["h"], c["w"]]
        lines.append(f"    // {r['comment']}")
        lines.append(
            f"    {{0x{r['vendor']:04x}, 0x{r['device']:04x}, "
            + ", ".join(str(v) for v in values)
            + f', "{r["variant"]}"}},'
        )
    lines += ["}};", "// clang-format on", "", "} // namespace vkcompute"]
    return "\n".join(lines) + "\n"


def by_device(dirs):
    groups = {}
    for d in dirs:
        name, s, ids = load(d)
        groups.setdefault(ids, []).append((name, s))
    return groups


def run_nominate(args, configs):
    nominations, decisions = {}, []
    for sessions in by_device(args.sessions).values():
        ref = sessions[0][1]
        dev = nominations.setdefault(ref["device"], {})
        for shape in ref["shapes"]:
            nomination, (info, code, text) = nominate(shape, sessions)
            dev[shape] = nomination
            c = configs[shape.removeprefix("sweep ")]
            decisions.append(record(ref, c, info, code, text))
    args.out.write_text(json.dumps(nominations, indent=1) + "\n")
    print(
        f"nominations for {sum(len(v) for v in nominations.values())} "
        f"configurations on {len(nominations)} devices"
    )
    return decisions


def check_confirmation(name, s):
    if not s.get("confirmation") or s.get("runs") != CONFIRM_RUNS:
        sys.exit(
            f"{name} is not a confirmation session of {CONFIRM_RUNS} runs: sweep "
            "sessions only nominate; the table is generated from confirmation "
            "sessions"
        )
    # Recorded by the session summary only when every run followed the
    # schedule of design D4 (each even run reverses the odd run before it).
    if s.get("schedule") != "paired-reverse":
        sys.exit(
            f"{name} did not run the confirmation schedule (paired-reverse): "
            "each even run must reverse the arm order of the odd run before it"
        )


def run_table(args, configs):
    nominations = {}
    for f in args.nominations or []:
        nominations.update(json.loads(f.read_text()))
    rows, decisions = [], []
    for ids, sessions in by_device(args.sessions).items():
        for name, s in sessions:
            check_confirmation(name, s)
        dev = sessions[-1][1]["device"]
        if dev not in nominations:
            sys.exit(f"no nominations for device {dev}")
        r, dec = rows_of(sessions, nominations[dev], ids, configs)
        rows += r
        decisions += dec
    text = header(rows)
    print(f"{len(rows)} rows from {len(decisions)} configurations")
    if args.check:
        if TABLE.read_text() != text:
            sys.exit(f"out of date: {TABLE.name}")
    else:
        TABLE.write_text(text)
    return decisions


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("step", choices=("nominate", "table"))
    parser.add_argument("sessions", type=Path, nargs="+")
    parser.add_argument("--out", type=Path, help="nominate: the nominations file")
    parser.add_argument(
        "--nominations", type=Path, nargs="+", help="table: nominate output files"
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--decisions", type=Path)
    args = parser.parse_args()
    configs = {c["label"]: c for c in json.loads(CONFIGS.read_text())}
    if args.step == "nominate":
        if args.out is None or args.check:
            sys.exit("nominate needs --out and writes no table")
        decisions = run_nominate(args, configs)
    else:
        decisions = run_table(args, configs)
    if args.decisions:
        args.decisions.write_text(json.dumps(decisions, indent=1) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""gen_exp.py: writes the experiment kernels of linexp-1/b70-4w from the release-zone 4w sources (read only):

  glsl/sarc_dev/sarc_exp_linear_q4gsw_coopmat_body.glslh   the release body + the EXP_* switches below
  glsl/sarc_dev/sarc_exp_linear_q4gsw_coopmat.glsl         the sweep template + the switches, including the body above
  glsl/sarc_dev/sarc_exp_linear_q4gsw_coopmat.yaml         the variants
  impl/sarc_dev/exp/ExpLinear.cpp                          candidate rows, fitting only while ET_VK_SARC_EXP=exp-*

Switches (all off = the release body, token for token):
  EXP_BCM 64|32   H2: B staged column-major WITHOUT padding (a B fragment = 16 columns x 16 K = one contiguous
                  512-byte run, a lane's column = 32 contiguous bytes) and loaded ColumnMajor; allowed together
                  with FRAG_LAYOUT. 64: `uvec2` elements (the body's B_COLMAJOR array), 32: `uint` elements.
  EXP_NOBARRIER   H3 ablation, INCORRECT BY CONSTRUCTION: no barrier before the multiply-adds of a K chunk.
  EXP_NOSTORE     H3 ablation, INCORRECT BY CONSTRUCTION: the staging stores of the next chunk are removed (the
                  compiler then also drops the fetches that fed them).
  EXP_NOFETCH     H3 ablation, INCORRECT BY CONSTRUCTION: the fetches of the next chunk are removed; the stores
                  stay and store the first chunk's values again.
"""
import os, re, sys
ET = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../.."))
G = ET + "/backends/vulkan/runtime/graph/ops/glsl"; I = ET + "/backends/vulkan/runtime/graph/ops/impl"


def sub(s, old, new, count=1):
    assert s.count(old) >= count, (old[:60], s.count(old))
    return s.replace(old, new, count)


b = open(G + "/sarc/sarc_linear_q4gsw_coopmat_body.glslh").read()
b = b.replace("SARC_LINEAR_Q4GSW_COOPMAT_BODY_GLSLH", "SARC_EXP_LINEAR_Q4GSW_COOPMAT_BODY_GLSLH")
b = sub(b, "// Body of the SARC q4gsw coopmat linear.", "// EXPERIMENT linexp-1/b70-4w (generated by exp/linexp-1/b70-4w/tools/gen_exp.py from\n// glsl/sarc/sarc_linear_q4gsw_coopmat_body.glslh; switches EXP_BCM, EXP_NOBARRIER, EXP_NOSTORE, EXP_NOFETCH).\n// Body of the SARC q4gsw coopmat linear.")
b = sub(b, '''#if defined(FRAG_LAYOUT)
#error "B_COLMAJOR is not combined with FRAG_LAYOUT"
#endif
const uint BT_STRIDE_H = WG_TILE_K + 8u;
const uint BT_STRIDE_V2 = BT_STRIDE_H / 4u;
const uint BT_SLICE = WG_TILE_N * BT_STRIDE_V2;
shared uvec2 BshT[2 * BT_SLICE];
''', '''#if defined(FRAG_LAYOUT) && !defined(EXP_BCM)
#error "B_COLMAJOR is not combined with FRAG_LAYOUT"
#endif
#ifdef EXP_BCM
// EXP_BCM: no padding, so the 16 columns of a B fragment are one contiguous run.
const uint BT_STRIDE_H = WG_TILE_K;
#else
const uint BT_STRIDE_H = WG_TILE_K + 8u;
#endif
const uint BT_STRIDE_V2 = BT_STRIDE_H / 4u;
const uint BT_SLICE = WG_TILE_N * BT_STRIDE_V2;
#if defined(EXP_BCM) && EXP_BCM == 32
#define BT_U 2u
shared uint BshT[2 * 2 * BT_SLICE];
#else
#define BT_U 1u
shared uvec2 BshT[2 * BT_SLICE];
#endif
''')
b = sub(b, '''    BshT[base + (n_local + j) * BT_STRIDE_V2 + k_local / 4u] =
        uvec2(packFloat2x16(v.xy), packFloat2x16(v.zw));
''', '''#if defined(EXP_BCM) && EXP_BCM == 32
    BshT[2u * (base + (n_local + j) * BT_STRIDE_V2 + k_local / 4u)] = packFloat2x16(v.xy);
    BshT[2u * (base + (n_local + j) * BT_STRIDE_V2 + k_local / 4u) + 1u] = packFloat2x16(v.zw);
#else
    BshT[base + (n_local + j) * BT_STRIDE_V2 + k_local / 4u] =
        uvec2(packFloat2x16(v.xy), packFloat2x16(v.zw));
#endif
''')
old = '''            matB, BshT,
            cur_base_B + n_b * BT_STRIDE_V2 + k_start / 4u,
            BT_STRIDE_V2,
'''
assert b.count(old) == 2
b = b.replace(old, '''            matB, BshT,
            BT_U * (cur_base_B + n_b * BT_STRIDE_V2 + k_start / 4u),
            BT_U * BT_STRIDE_V2,
''')
old = '''    // `coopmat-lds-needs-explicit-memorybarriershared`.
    memoryBarrierShared();
    barrier();
'''
n = [m.start() for m in re.finditer(re.escape(old), b)]
assert len(n) >= 2, len(n)
new = '''    // `coopmat-lds-needs-explicit-memorybarriershared`.
#ifndef EXP_NOBARRIER
    memoryBarrierShared();
    barrier();
#endif
'''
b = b[:n[0]] + new + b[n[0] + len(old):n[1]] + new + b[n[1] + len(old):]  # the K loop and its peeled last chunk only
b = sub(b, "    // --- prefetch chunk+1 -> temp ---\n    {\n", "    // --- prefetch chunk+1 -> temp ---\n#ifndef EXP_NOFETCH\n    {\n")
b = sub(b, "    }\n\n    // --- MMA math on the cur slice ---\n", "    }\n#endif // EXP_NOFETCH\n\n    // --- MMA math on the cur slice ---\n")
b = sub(b, "    // --- store temp (chunk+1) -> nxt slice, dequantizing B ---\n    {\n", "    // --- store temp (chunk+1) -> nxt slice, dequantizing B ---\n#ifndef EXP_NOSTORE\n    {\n")
b = sub(b, "    }\n  }\n\n  // --- epilogue: barrier, then MMA on the last chunk (loop peeled) ---\n", "    }\n#endif // EXP_NOSTORE\n  }\n\n  // --- epilogue: barrier, then MMA on the last chunk (loop peeled) ---\n")
open(G + "/sarc_dev/sarc_exp_linear_q4gsw_coopmat_body.glslh", "w").write(b)

t = open(G + "/sarc_dev/sarc_linear_q4gsw_coopmat_sweep.glsl").read()
t = sub(t, '#include "sarc_linear_q4gsw_coopmat_body.glslh"', '''// EXPERIMENT linexp-1/b70-4w switches (see the body's header).
$if EXP_BCM != 0:
  #define EXP_BCM ${EXP_BCM}

$if EXP_NOBARRIER:
  #define EXP_NOBARRIER

$if EXP_NOSTORE:
  #define EXP_NOSTORE

$if EXP_NOFETCH:
  #define EXP_NOFETCH

#include "sarc_exp_linear_q4gsw_coopmat_body.glslh"''')
open(G + "/sarc_dev/sarc_exp_linear_q4gsw_coopmat.glsl", "w").write(t)

# (tag, grid x, grid y, subgroup, switches)
BASE = dict(FRAG_LAYOUT="true", IMG_A="true", CSH_BAND="true")
V = [
    ("ctl", 8, 2, 16, {}),
    ("bcm64", 8, 2, 16, dict(B_COLMAJOR="true", EXP_BCM=64)),
    ("bcm32", 8, 2, 16, dict(B_COLMAJOR="true", EXP_BCM=32)),
    ("bcm64", 4, 4, 16, dict(B_COLMAJOR="true", EXP_BCM=64)),
    ("bcm32", 4, 4, 16, dict(B_COLMAJOR="true", EXP_BCM=32)),
    ("nobar", 8, 2, 16, dict(EXP_NOBARRIER="true")),
    ("nostore", 8, 2, 16, dict(EXP_NOSTORE="true")),
    ("nofetch", 8, 2, 16, dict(EXP_NOFETCH="true")),
    ("nobarnostore", 8, 2, 16, dict(EXP_NOBARRIER="true", EXP_NOSTORE="true")),
    ("s32", 4, 2, 32, {}),
    ("s32", 8, 2, 32, {}),
]
y = ['''# EXPERIMENT linexp-1/b70-4w (generated by exp/linexp-1/b70-4w/tools/gen_exp.py). Never referenced by a table;
# rows in impl/sarc_dev/exp/ExpLinear.cpp fit only while ET_VK_SARC_EXP starts with "exp-".
# nobar / nostore / nofetch / nobarnostore are timing-only ablations, INCORRECT BY CONSTRUCTION.

sarc_exp_linear_q4gsw_coopmat:
  parameter_names_with_default_values:
    PRECISION: highp
    HAS_BIAS: false
    IO_STORAGE: texture3d
    WEIGHT_STORAGE: texture2d
    MMA_M: 8
    MMA_N: 16
    MMA_K: 16
    WG_TILE_M: 128
    WG_TILE_N: 128
    WG_TILE_K: 16
    SG_GRID_X: 8
    SG_GRID_Y: 2
    SUBGROUP_SIZE: 16
    ACC_FP32: false
    CSH_IN_ASH: false
    ACC_GROUP_FP32: false
    ACC_GROUP_FP32_REG: false
    FRAG_LAYOUT: true
    IMG_A: true
    IMG_W: false
    SH_F16V4: false
    CSH_BAND: true
    B_COLMAJOR: false
    CSH_FULL: false
    CSH_POOL: false
    EXP_BCM: 0
    EXP_NOBARRIER: false
    EXP_NOSTORE: false
    EXP_NOFETCH: false
  shader_variants:''']
rows = []
for tag, gx, gy, sg, sw in V:
    base = f"sarc_exp_linear_q4gsw_coopmat_{tag}_t128x128k16g{gx}{gy}s{sg}m8flib"
    y.append(f"    - NAME: {base}_texture3d_texture2d_half\n      SG_GRID_X: {gx}\n      SG_GRID_Y: {gy}\n      SUBGROUP_SIZE: {sg}" + "".join(f"\n      {k}: {v}" for k, v in sw.items()))
    rows.append(f'    {{"", nullptr, Op::kQ4gswLinear,\n     "{base}",\n     {{128, 128, 16, {gx}, {gy}, {sg}, 8, false}}, kTex3dTex2d, exp_requested, Status::kUnverified}},')
open(G + "/sarc_dev/sarc_exp_linear_q4gsw_coopmat.yaml", "w").write("\n".join(y) + "\n")
open(I + "/sarc_dev/exp/ExpLinear.cpp", "w").write('''/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 * All rights reserved.
 *
 * This source code is licensed under the BSD-style license found in the
 * LICENSE file in the root directory of this source tree.
 */

// EXPERIMENT linexp-1/b70-4w (generated by exp/linexp-1/b70-4w/tools/gen_exp.py): twins of the Xe2 4w kernel
// (glsl/sarc_dev/sarc_exp_linear_q4gsw_coopmat.yaml). Candidate rows: never chosen by a table; a row fits only
// while ET_VK_SARC_EXP starts with "exp-", and is then selected by name with ET_VK_SARC_Q4GSW_VARIANT (which
// needs ET_VK_SARC_UNVERIFIED=1). The nobar / nostore / nofetch / nobarnostore rows are timing-only ablations
// that are INCORRECT BY CONSTRUCTION.

#include <executorch/backends/vulkan/runtime/graph/ops/impl/sarc/Select.h>

#include <cstdlib>
#include <cstring>

namespace vkcompute {
namespace sarc {
namespace {

bool exp_requested(const ShapeInfo&) {
  const char* e = std::getenv("ET_VK_SARC_EXP");
  return e != nullptr && std::strncmp(e, "exp-", 4) == 0;
}

const Row kExpLinearCandidates[] = {
''' + "\n".join(rows) + '''
};

struct Registrar {
  Registrar() {
    register_candidates(
        kExpLinearCandidates,
        sizeof(kExpLinearCandidates) / sizeof(kExpLinearCandidates[0]));
  }
} registrar;

} // namespace
} // namespace sarc
} // namespace vkcompute
''')
print("written", len(V), "variants")

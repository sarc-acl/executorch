#!/usr/bin/env python3
"""gen_exp.py <executorch tree>: experiment linexp-1/b580-reuse, H1 test 2. Writes (idempotently) NEW dev-zone files only:

  glsl/sarc_dev/sarc_exp_linear_dq8ca_coopmat_zpg_body.glslh   derived from the incumbent's body
                                                              (sarc_dev_linear_dq8ca_coopmat_zpg_xe2bt_body.glslh, read-only)
  glsl/sarc_dev/sarc_exp_linear_dq8ca_coopmat_zpg.glsl / .yaml
  impl/sarc_dev/exp/ExpLinear.cpp                             candidate rows, selected by name and gated (see below)

Two modes, both without fp32 totals held in registers across the K loop:
  sh   (task variant a, CORRECT): at every group end the int32 accumulators are dequantized (x weight scale) and
       added to fp32 totals that live in shared memory (tot_sh, column-major, one disjoint region per subgroup);
       the activation correction is applied in place at the end and the whole workgroup drains tot_sh to the
       image. Same arithmetic per output element and same summation order as the incumbent. The totals need
       4 * WG_TILE_M * WG_TILE_N bytes, so only tiles of 8192 elements fit (64 x 128, K chunk 32).
  i32  (task variant b, ABLATION, INCORRECT BY CONSTRUCTION for more than one quantization group): the int32
       accumulators run across all groups and are scaled once at the end with the last group's scale. Identical
       arithmetic only when the weight has one quantization group (K <= group size) or equal scales in all
       groups; every production shape has 16 to 112 groups. Timing-only; never a result.

Selection: rows are candidates (never chosen by a table), status kUnverified, and their shape predicate holds
only while ET_VK_SARC_EXP starts with "exp-". So a kernel runs only with ET_VK_SARC_UNVERIFIED=1,
ET_VK_SARC_EXP=exp-<anything> and ET_VK_SARC_DQ8CA_VARIANT=<its token>.
"""
import pathlib, sys

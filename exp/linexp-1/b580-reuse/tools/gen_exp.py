g = root / "glsl/sarc_dev"; impl = root / "impl/sarc_dev/exp"; impl.mkdir(exist_ok=True)
SRC = "sarc_dev_linear_dq8ca_coopmat_zpg_xe2bt"; DST = "sarc_exp_linear_dq8ca_coopmat_zpg"
LDS_LIMIT = 49152

def rep(text, old, new, count=1):
    assert text.count(old) == count, f"{text.count(old)} occurrences (want {count}) of: {old[:70]!r}"
    return text.replace(old, new)

def cut(text, begin, end):
    """text before `begin`, text from `end` on (both anchors unique)."""
    assert text.count(begin) == 1 and text.count(end) == 1, (begin[:50], text.count(begin), end[:50], text.count(end))
    return text[:text.index(begin)], text[text.index(end):]

ACC = "coopmat<float, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator>"

# ---------------------------------------------------------------- body
b = (g / f"{SRC}_body.glslh").read_text()
b = rep(b, "SARC_DEV_LINEAR_DQ8CA_COOPMAT_ZPG_XE2BT_BODY_GLSLH", "SARC_EXP_LINEAR_DQ8CA_COOPMAT_ZPG_BODY_GLSLH", 3)
b = rep(b, "// GENERATED by gen_bt.py from the release zpg body (texel-wise B staging). Body of sarc_dev_linear_dq8ca_coopmat_zpg_bt;",
        "// GENERATED by exp/linexp-1/b580-reuse/tools/gen_exp.py from sarc_dev_linear_dq8ca_coopmat_zpg_xe2bt_body.glslh\n"
        "// (experiment linexp-1/b580-reuse: no fp32 totals in registers across the K loop; EXP_TOT_SH or EXP_I32_ONLY).\n"
        "// Original header: body of sarc_dev_linear_dq8ca_coopmat_zpg_bt;")
b = rep(b, """// Running fp32 accumulator (across all groups).
coopmat<float, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator>
    result[MMAS_PER_SG_M][MMAS_PER_SG_N];
""", """#if defined(EXP_TOT_SH) == defined(EXP_I32_ONLY)
#error exactly one of EXP_TOT_SH, EXP_I32_ONLY
#endif
#if !defined(IO_TEXTURE) || !defined(WEIGHT_INT4) || defined(HAS_BIAS)
#error the experiment kernels are texture3d, 4-bit weight, no bias only
#endif
#ifdef EXP_TOT_SH
// exp (a): fp32 totals of the whole workgroup tile, column-major (element (m, n) at n * WG_TILE_M + m), so a
// lane of an 8 x 16 accumulator (one column, 8 rows) is 8 contiguous words. Each subgroup owns the region of
// its own output block.
shared float tot_sh[WG_TILE_M * WG_TILE_N];
#define TOT_OFF(i, j) ((MMA_N * (MMAS_PER_SG_N * warpInTile.x + (j))) * WG_TILE_M + MMA_M * (MMAS_PER_SG_M * warpInTile.y + (i)))
#endif
""")
b = rep(b, "#ifdef IO_TEXTURE\n// Result staging for the imageStore epilogue", "#ifndef EXP_TOT_SH\n// Result staging for the imageStore epilogue")
b = rep(b, f"      result[i][j] = {ACC}(0.0);\n", "")
# group epilog
head, tail = cut(b, "    // --- Group epilog: scale-only accumulate, reset accum ---", "  }  // groups")
b = head + f"""    // --- Group epilog ---
#ifdef EXP_TOT_SH
    // exp (a): tot_sh += float(acc) * wsc, then reset acc. The store of group g is read by the epilog of group
    // g + 1 after at least one chunk barrier.
    {{
      const uint wbase = (group_i % 2u) * WG_TILE_N;
      [[unroll]] for (uint j = 0; j < MMAS_PER_SG_N; ++j) {{
        const uint local_n_base = MMA_N * (MMAS_PER_SG_N * warpInTile.x + j);
        {ACC} wsc_bcast;
        coopMatLoad(
            wsc_bcast, wsc_sh,
            wbase + local_n_base, /*stride=*/0u,
            gl_CooperativeMatrixLayoutRowMajor);
        [[unroll]] for (uint i = 0; i < MMAS_PER_SG_M; ++i) {{
          {ACC} t =
              {ACC}(accum_int32[i][j]) * wsc_bcast;
          if (group_i > 0u) {{
            {ACC} prev;
            coopMatLoad(prev, tot_sh, TOT_OFF(i, j), WG_TILE_M, gl_CooperativeMatrixLayoutColumnMajor);
            t += prev;
          }}
          coopMatStore(t, tot_sh, TOT_OFF(i, j), WG_TILE_M, gl_CooperativeMatrixLayoutColumnMajor);
          accum_int32[i][j] = coopmat<int32_t, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator>(0);
        }}
      }}
    }}
#endif
    // exp (b), EXP_I32_ONLY: nothing here; the int32 accumulators run on across the groups (ABLATION).
""" + tail
# everything after the group loop
head, tail = cut(b, "  // --- Hoisted correction, applied ONCE: ---", "#endif // SARC_EXP_LINEAR_DQ8CA_COOPMAT_ZPG_BODY_GLSLH")
b = head + f"""#ifdef EXP_TOT_SH
  // exp (a): result = ifs * (tot - izp * SUM_g wsc_g*wsum_g), in place in tot_sh, then the workgroup drains it.
  memoryBarrierShared();
  barrier();
  {{
    {ACC}
        izpf_bcast[MMAS_PER_SG_M];
    {ACC}
        ifs_bcast[MMAS_PER_SG_M];
    [[unroll]] for (uint i = 0; i < MMAS_PER_SG_M; ++i) {{
      const uint local_m_base = MMA_M * (MMAS_PER_SG_M * warpInTile.y + i);
      coopmat<int32_t, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator> izp_i;
      coopMatLoad(
          izp_i, izp_sh, local_m_base, /*stride=*/0u,
          gl_CooperativeMatrixLayoutColumnMajor);
      izpf_bcast[i] =
          {ACC}(izp_i);
      coopMatLoad(
          ifs_bcast[i], ifs_sh, local_m_base, /*stride=*/0u,
          gl_CooperativeMatrixLayoutColumnMajor);
    }}
    [[unroll]] for (uint j = 0; j < MMAS_PER_SG_N; ++j) {{
      const uint local_n_base = MMA_N * (MMAS_PER_SG_N * warpInTile.x + j);
      {ACC} wcorr_bcast;
      coopMatLoad(
          wcorr_bcast, wcorr_sh, local_n_base, /*stride=*/0u,
          gl_CooperativeMatrixLayoutRowMajor);
      [[unroll]] for (uint i = 0; i < MMAS_PER_SG_M; ++i) {{
        {ACC} t;
        coopMatLoad(t, tot_sh, TOT_OFF(i, j), WG_TILE_M, gl_CooperativeMatrixLayoutColumnMajor);
        t = ifs_bcast[i] * (t - izpf_bcast[i] * wcorr_bcast);
        coopMatStore(t, tot_sh, TOT_OFF(i, j), WG_TILE_M, gl_CooperativeMatrixLayoutColumnMajor);
      }}
    }}
  }}
  memoryBarrierShared();
  barrier();
  {{
    const uint TEXELS_PER_ROW = WG_TILE_N / 4u;
    for (uint t = gl_LocalInvocationID.x; t < WG_TILE_M * TEXELS_PER_ROW; t += WG_SIZE) {{
      const uint lr = t / TEXELS_PER_ROW;
      const uint lc4 = t % TEXELS_PER_ROW;
      const uint base = (lc4 * 4u) * WG_TILE_M + lr;
      // float16_t round trip: the incumbent converts its result tile to fp16 before the store.
      imageStore(
          t_output,
          ivec3(tile_n_start / 4u + lc4, tile_m_start + lr, 0),
          vec4(
              float(float16_t(tot_sh[base])),
              float(float16_t(tot_sh[base + WG_TILE_M])),
              float(float16_t(tot_sh[base + 2u * WG_TILE_M])),
              float(float16_t(tot_sh[base + 3u * WG_TILE_M]))));
    }}
  }}
#else
  // exp (b), ABLATION: one conversion at the end with the LAST group's scale (wrong for more than one group),
  // computed per row block inside the incumbent's drain so that no fp32 tile outlives an iteration.
  const uint wbase_last = ((num_groups - 1u) % 2u) * WG_TILE_N;
  const uint CSH_TEXELS_PER_ROW = WG_TILE_N / 4u;
  const uint CSH_TEXELS = CSH_ROWS * CSH_TEXELS_PER_ROW;
  [[unroll]] for (uint i = 0; i < MMAS_PER_SG_M; ++i) {{
    memoryBarrierShared();
    barrier();
    const uint local_m_base = MMA_M * (MMAS_PER_SG_M * warpInTile.y + i);
    coopmat<int32_t, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator> izp_i;
    coopMatLoad(izp_i, izp_sh, local_m_base, /*stride=*/0u, gl_CooperativeMatrixLayoutColumnMajor);
    {ACC} ifs_b;
    coopMatLoad(ifs_b, ifs_sh, local_m_base, /*stride=*/0u, gl_CooperativeMatrixLayoutColumnMajor);
    [[unroll]] for (uint j = 0; j < MMAS_PER_SG_N; ++j) {{
      const uint local_n_base = MMA_N * (MMAS_PER_SG_N * warpInTile.x + j);
      {ACC} wsc_b;
      coopMatLoad(wsc_b, wsc_sh, wbase_last + local_n_base, /*stride=*/0u, gl_CooperativeMatrixLayoutRowMajor);
      {ACC} wcorr_b;
      coopMatLoad(wcorr_b, wcorr_sh, local_n_base, /*stride=*/0u, gl_CooperativeMatrixLayoutRowMajor);
      {ACC} r =
          ifs_b * ({ACC}(accum_int32[i][j]) * wsc_b
                   - {ACC}(izp_i) * wcorr_b);
      coopmat<float16_t, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator> out_tile =
          coopmat<float16_t, gl_ScopeSubgroup, MMA_M, MMA_N, gl_MatrixUseAccumulator>(r);
      coopMatStore(
          out_tile, Csh_out,
          warpInTile.y * MMA_M * WG_TILE_N + local_n_base,
          WG_TILE_N,
          gl_CooperativeMatrixLayoutRowMajor);
    }}
    memoryBarrierShared();
    barrier();
    for (uint t = gl_LocalInvocationID.x; t < CSH_TEXELS; t += WG_SIZE) {{
      const uint lr = t / CSH_TEXELS_PER_ROW;
      const uint lc4 = t % CSH_TEXELS_PER_ROW;
      const uint m =
          tile_m_start + (lr / MMA_M) * SG_TILE_M + i * MMA_M + (lr % MMA_M);
      const uint base = lr * WG_TILE_N + lc4 * 4u;
      imageStore(
          t_output,
          ivec3(tile_n_start / 4u + lc4, m, 0),
          vec4(
              float(Csh_out[base]),
              float(Csh_out[base + 1u]),
              float(Csh_out[base + 2u]),
              float(Csh_out[base + 3u])));
    }}
  }}
#endif
}}

""" + tail

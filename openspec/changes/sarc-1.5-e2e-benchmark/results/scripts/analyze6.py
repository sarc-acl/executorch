"""Aggregate the e2e campaign: raw/<gpu>/runs.csv -> report/{runs_all,cells}.csv + tables.md.

Per cell (gpu, model, scheme, build): median, min, max, n, bootstrap 95 % CI of the median.
Speedup per (gpu, model, scheme): median(sarc) / median(stock). Its approximate 95 % CI is a
paired percentile bootstrap: the design pairs the two builds within each repeat (back to back,
interleaved order), so repeat indices are resampled and the same indices are used for both arms
(20000 draws, fixed seed). With n = 5 the percentiles sit near the extreme order statistics, so
coverage is approximate. The unpaired interval (arms resampled independently, conservative) and
the median of per-repeat paired ratios are reported alongside. Geomeans per scheme, GPU, overall.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

C = Path(__file__).resolve().parent.parent
GPUS = ["780m", "b580", "b70", "4070ti", "orin", "7900xtx"]
GPU_LABEL = {
    "780m": "Radeon 780M",
    "b580": "Arc B580",
    "b70": "Arc Pro B70",
    "4070ti": "RTX 4070 Ti SUPER",
    "orin": "Jetson Orin Nano",
    "7900xtx": "RX 7900 XTX (pre-release)",
}
MODELS = ["1b", "3b", "8b"]
MODEL_LABEL = {"1b": "Llama 3.2 1B", "3b": "Llama 3.2 3B", "8b": "Llama 3.1 8B"}
SCHEMES = ["4w", "8da4w"]
RNG = np.random.default_rng(20260928)
NBOOT = 20000


def boot_median(x):
    x = np.asarray(x)
    idx = RNG.integers(0, len(x), size=(NBOOT, len(x)))
    return np.median(x[idx], axis=1)


def main():
    sub = sys.argv[1] if len(sys.argv) > 1 else "raw"
    OUT = C / "report" / ("." if sub == "raw" else sub.replace("raw_", ""))
    OUT.mkdir(parents=True, exist_ok=True)
    frames = []
    for g in GPUS:
        p = C / sub / g / "runs.csv"
        if p.exists():
            frames.append(pd.read_csv(p, dtype={"rep": str}))
    runs = pd.concat(frames, ignore_index=True)
    runs["kind"] = np.where(runs["log"].str.startswith("logs/prefill"), "prefill", "check")
    runs.to_csv(OUT / "runs_all.csv", index=False)
    pre = runs[runs.kind == "prefill"]
    ok = pre[(pre.rc == 0) & pre.tok_s.notna()]
    rejected = pre[~pre.index.isin(ok.index)]

    rows = []
    for (g, m, q), cell in ok.groupby(["gpu", "model", "scheme"]):
        rec = {"gpu": g, "model": m, "scheme": q}
        arms = {}
        for b in ["stock", "sarc"]:
            x = cell[cell.build == b].tok_s.to_numpy()
            arms[b] = x
            bm = boot_median(x)
            rec.update({
                f"{b}_n": len(x),
                f"{b}_median": float(np.median(x)),
                f"{b}_min": float(x.min()),
                f"{b}_max": float(x.max()),
                f"{b}_ci_lo": float(np.percentile(bm, 2.5)),
                f"{b}_ci_hi": float(np.percentile(bm, 97.5)),
                f"{b}_spread_pct": float((x.max() / x.min() - 1) * 100),
            })
        rec["speedup"] = rec["sarc_median"] / rec["stock_median"]
        unp = boot_median(arms["sarc"]) / boot_median(arms["stock"])
        rec["speedup_unpaired_ci_lo"] = float(np.percentile(unp, 2.5))
        rec["speedup_unpaired_ci_hi"] = float(np.percentile(unp, 97.5))
        pr = cell[cell.rep.str.fullmatch(r"\d+")].pivot_table(index="rep", columns="build", values="tok_s").dropna()
        st, sa = pr["stock"].to_numpy(), pr["sarc"].to_numpy()
        idx = RNG.integers(0, len(st), size=(NBOOT, len(st)))
        paired = np.median(sa[idx], axis=1) / np.median(st[idx], axis=1)
        rec["speedup_ci_lo"] = float(np.percentile(paired, 2.5))
        rec["speedup_ci_hi"] = float(np.percentile(paired, 97.5))
        rec["n_pairs"] = len(st)
        rec["median_paired_ratio"] = float(np.median(sa / st))
        rows.append(rec)
    cells = pd.DataFrame(rows)

    nt = []
    for g in GPUS:
        p = C / sub / g / "nexttoken.csv"
        if p.exists():
            d = pd.read_csv(p, header=None, names=["model", "scheme", "next_token"])
            d["gpu"] = g
            nt.append(d)
    if nt:
        cells = cells.merge(pd.concat(nt), on=["gpu", "model", "scheme"], how="left")
    cells["gpu_label"] = cells.gpu.map(GPU_LABEL)
    cells["model_label"] = cells.model.map(MODEL_LABEL)
    order = {g: i for i, g in enumerate(GPUS)}
    cells = cells.sort_values(
        ["scheme", "gpu", "model"], key=lambda s: s.map(order) if s.name == "gpu" else s
    )
    cells.to_csv(OUT / "cells.csv", index=False)

    gm = lambda s: float(np.exp(np.log(s).mean()))
    out = ["# Tables (generated by analyze.py)\n"]
    for q in SCHEMES:
        out.append(f"\n## {q}: prefill tok/s (2048 tokens), median of n runs [95 % CI]\n")
        out.append("| GPU | Model | stock 1.5 | SARC r2 | speedup [paired 95 % CI] | spread stock/sarc | next token |")
        out.append("|---|---|---|---|---|---|---|")
        for _, r in cells[cells.scheme == q].iterrows():
            out.append(
                f"| {r.gpu_label} | {r.model_label} | {r.stock_median:.1f} [{r.stock_ci_lo:.1f}, {r.stock_ci_hi:.1f}] (n={r.stock_n}) "
                f"| {r.sarc_median:.1f} [{r.sarc_ci_lo:.1f}, {r.sarc_ci_hi:.1f}] (n={r.sarc_n}) "
                f"| **{r.speedup:.2f}×** [{r.speedup_ci_lo:.2f}, {r.speedup_ci_hi:.2f}] "
                f"| {r.stock_spread_pct:.1f} % / {r.sarc_spread_pct:.1f} % | {r.get('next_token', '')} |"
            )
    out.append("\n## Geometric-mean speedup\n")
    out.append("| GPU | 4w | 8da4w | both |")
    out.append("|---|---|---|---|")
    for g in GPUS:
        c = cells[cells.gpu == g]
        if c.empty:
            continue
        out.append(
            f"| {GPU_LABEL[g]} | {gm(c[c.scheme=='4w'].speedup):.2f}× | {gm(c[c.scheme=='8da4w'].speedup):.2f}× | {gm(c.speedup):.2f}× |"
        )
    out.append(
        f"| **all** | {gm(cells[cells.scheme=='4w'].speedup):.2f}× | {gm(cells[cells.scheme=='8da4w'].speedup):.2f}× | {gm(cells.speedup):.2f}× |"
    )
    flags = cells[(cells.stock_spread_pct > 3) | (cells.sarc_spread_pct > 3)]
    out.append(f"\n## Quality flags\n\n- cells with repeat spread > 3 %: {len(flags)}")
    for _, r in flags.iterrows():
        out.append(f"  - {r.gpu} {r.model} {r.scheme}: stock {r.stock_spread_pct:.1f} %, sarc {r.sarc_spread_pct:.1f} %")
    if "next_token" in cells:
        bad = cells[cells.next_token != "SAME"]
        out.append(f"- next-token mismatches (sarc vs stock, prompt_check.txt): {len(bad)}")
        for _, r in bad.iterrows():
            out.append(f"  - {r.gpu} {r.model} {r.scheme}: {r.next_token}")
    out.append(f"- rejected prefill runs (kept in runs_all.csv): {len(rejected)}")
    for _, r in rejected.iterrows():
        out.append(f"  - {r.gpu} {r.model} {r.scheme} {r.build} rep {r.rep}: rc={r.rc} tok_s={r.tok_s}")
    (OUT / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
